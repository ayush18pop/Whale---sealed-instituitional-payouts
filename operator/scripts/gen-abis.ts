// Generates src/abis.ts from contracts/out (run after `forge build` in contracts/).
import { readFileSync, writeFileSync } from "node:fs";
const names: [string, string][] = [
  ["Hub", "Hub.sol"], ["MainBridge", "MainBridge.sol"], ["MockSwap", "MockSwap.sol"],
  ["TestUSDC", "TestUSDC.sol"], ["DomainToken", "domain/DomainToken.sol"], ["Treasury", "domain/Treasury.sol"],
  ["UniswapV4Adapter", "UniswapV4Adapter.sol"], ["PoolSeeder", "PoolSeeder.sol"],
];
let out = "// GENERATED by scripts/gen-abis.ts from contracts/out. Do not edit.\n";
for (const [n] of names) {
  const j = JSON.parse(readFileSync(new URL(`../../contracts/out/${n}.sol/${n}.json`, import.meta.url), "utf8"));
  out += `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(j.abi)} as const;\n`;
}
writeFileSync(new URL("../src/abis.ts", import.meta.url), out);
